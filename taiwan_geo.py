def resolve_taiwan_location(lat: float, lng: float, stop_name: str = "") -> dict:
    best_county = "其他地區"
    best_district = ""
    best_region = "其他"

    min_dist_sq = 9999.0
    for p_lat, p_lng, c_name, d_name in DISTRICT_POINTS:
        d_sq = (lat - p_lat) ** 2 + (lng - p_lng) ** 2
        if d_sq < min_dist_sq:
            min_dist_sq = d_sq
            best_county = c_name
            best_district = d_name

    if min_dist_sq > 0.08:
        for b in COUNTY_BOUNDS:
            if b["lat_min"] <= lat <= b["lat_max"] and b["lng_min"] <= lng <= b["lng_max"]:
                best_county = b["name"]
                best_region = b["region"]
                break

    best_region = REGION_GROUPS.get(best_county, "其他")
    area_name = f"{best_county}{best_district}" if best_district else best_county

    clean_stop_name = stop_name.strip() if stop_name else ""
    if clean_stop_name and clean_stop_name not in ["未命名補給站", "未知補給站"]:
        full_address = f"{area_name} · {clean_stop_name}"
    else:
        full_address = f"{area_name} (經緯度 {lat:.4f}, {lng:.4f})"

    return {
        "county": best_county,
        "district": best_district,
        "area_name": area_name,
        "full_address": full_address,
        "region_group": best_region
    }
